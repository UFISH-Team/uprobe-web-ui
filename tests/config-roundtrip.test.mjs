const {restoreTemplate,validateProbeDependencies,exportAttribute}=load('src/utils/probeConfig.ts');
const fixture={extracts:{target_region:{source:'exon',length:40,overlap:0}},probes:{pad:{template:'{part1}',parts:{part1:{expr:'target_region',attributes:{kmer_count:{enabled:true,kmer_len:21,aligner:'Jellyfish'}}}}}},attributes:{a:{target:'target_region',type:'fold_score'},b:{target:'pad.part1',type:'annealing_temperature'},c:{target:'pad.part1',type:'annealing_temperature'}},post_process:{filters:{a:{condition:'a <= 0'},b:{condition:'b > 36 & b <= 44'},ends:{type:'sequence_pattern',target:'pad',exclude_patterns:['(?P<base>[ACGT])(?P=base){3,}']},composite:{condition:'a < 1 | b > 40'}},sorts:{is_ascending:['a'],is_descending:['b']}}};
