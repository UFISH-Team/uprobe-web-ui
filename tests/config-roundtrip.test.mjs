assert.throws(()=>restoreTemplate({...fixture,attributes:{bad:{target:'missing.part',type:'fold_score'}}}),/missing sequence/);
assert.equal(validateProbeDependencies([{id:'1',name:'one',parts:[]},{id:'2',name:'two',parts:[{source:'probe',sourceProbeId:'1'}]}]),'');
